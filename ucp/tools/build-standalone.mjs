/* ===========================================================================
   Build single-file copies of the RETAIL pages.
   ---------------------------------------------------------------------------
   The prototype normally loads six sibling files (two stylesheets, three
   scripts, two logos). That is fine on a dev server and useless on a phone,
   where you cannot serve a folder.

   This inlines every local dependency so each page is ONE self-contained file
   that opens straight from a Downloads folder. The two things left external
   are the two things a phone can reach and this container cannot:
     · Google Fonts  — Zain and IBM Plex Sans Arabic
     · ucpksa.com    — the real product photography

   So these files are the only way to see the design with UCP's own photographs
   until the network policy here allows ucpksa.com.

   Cross-page links keep their original filenames, so all three files sitting in
   the same folder navigate between each other.

   Run:  node ucp/tools/build-standalone.mjs
   =========================================================================== */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, "../design/ninja");
const OUT = join(here, "../design/standalone");
mkdirSync(OUT, { recursive: true });

const read = (f) => readFileSync(join(SRC, f), "utf8");
const dataUri = (f, mime) =>
  "data:" + mime + ";base64," + readFileSync(join(SRC, f)).toString("base64");

const CSS = { "ucp.css": read("ucp.css"), "retail.css": read("retail.css") };
const JS = { "catalogue.js": read("catalogue.js"), "ucp.js": read("ucp.js"), "retail.js": read("retail.js") };
const MARK = dataUri("../brand/ucp-mark.png", "image/png");
const LOCK = dataUri("../brand/ucp-lockup.png", "image/png");

/* A </script> inside a string literal would close the inlined block early. */
const safeJs = (s) => s.replace(/<\/script>/gi, "<\\/script>");

const PAGES = ["e-retail.html", "e-list.html", "e-product.html"];
let total = 0;

for (const page of PAGES) {
  let h = read(page);

  for (const [name, css] of Object.entries(CSS)) {
    const tag = `<link rel="stylesheet" href="${name}">`;
    if (!h.includes(tag)) throw new Error(`${page}: missing ${tag}`);
    h = h.replace(tag, `<style>/* ${name} */\n${css}</style>`);
  }
  for (const [name, js] of Object.entries(JS)) {
    const tag = `<script src="${name}"></script>`;
    if (!h.includes(tag)) continue;               // not every page loads every script
    h = h.replace(tag, `<script>/* ${name} */\n${safeJs(js)}</script>`);
  }

  h = h.split('"../brand/ucp-mark.png"').join(`"${MARK}"`);
  h = h.split('"../brand/ucp-lockup.png"').join(`"${LOCK}"`);
  h = h.split("src=\"../brand/ucp-mark.png\"").join(`src="${MARK}"`);
  h = h.split("src=\"../brand/ucp-lockup.png\"").join(`src="${LOCK}"`);

  // a banner so nobody mistakes a downloaded copy for the source of truth
  h = h.replace("</title>",
    "</title>\n<!-- Single-file build. Generated by ucp/tools/build-standalone.mjs;"
    + " edit ucp/design/ninja/ and re-run, never this file. -->");

  if (/href="(ucp|retail)\.(css|js)"|src="(catalogue|ucp|retail)\.js"/.test(h))
    throw new Error(`${page}: a local dependency survived inlining`);
  if (h.includes("../brand/")) throw new Error(`${page}: a logo path survived inlining`);

  writeFileSync(join(OUT, page), h);
  total += h.length;
  console.log(`${page.padEnd(18)} ${(h.length / 1024 / 1024).toFixed(2)} MB`);
}
console.log(`\n${PAGES.length} files, ${(total / 1024 / 1024).toFixed(2)} MB total`);
console.log("External at runtime: Google Fonts + ucpksa.com photographs only.");
